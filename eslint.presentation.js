// eslint.presentation.js
//
// The seam, in machine-checkable form. Spread into eslint.config.js:
//
//   import { presentationRules } from "./eslint.presentation.js";
//   export default tseslint.config([ ...baseline, ...presentationRules ]);
//
// ─── Why this file is TWO tiers and the antd/MUI/Carbon versions were one ───
//
// Those libraries lived in node_modules. shadcn does not: `npx shadcn add`
// COPIES component source into src/components/ui/. That source is raw <button>,
// <table> and <input>, it sets style={{ transform }} in progress.tsx, it writes
// text-white in the destructive variants of button and badge, bg-black/50 for
// the dialog and sheet scrims, and [&_.recharts-dot[stroke='#fff']] selectors
// in chart.tsx. Every one of those is legitimate. A single-tier config lifted
// from the antd pack fails on `shadcn add` output before the designer has
// written a line — verified by running these rules against the real registry
// source, not by reading it.
//
// So:
//   VENDORED (src/components/ui/**) — designer-OWNED and editable, but it is
//     generated code. Constrain what a designer ADDS; don't fight what the CLI
//     WROTE. Logic bans + the two class rules that came back 100% clean.
//   AUTHORED (flows, shared/ui, features/*/ui, stories) — hand-written by the
//     designer. Full ruleset.
//
// Both tiers are DESIGNER territory. This is not an ownership split, it's a
// generated-vs-authored split.

